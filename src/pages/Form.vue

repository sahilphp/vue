<template>
    <AppLayout :app-name="appName ?? 'SahilPHP'">
        <div class="form-page">
            <h1 class="form-page__title">Contact form</h1>
            <p class="form-page__note">
                Submit this form to see server-provided validation messages. No network request
                is made; the demo feeds simulated errors the same way a controller response would.
            </p>

            <FormField
                v-model="email"
                name="email"
                label="Email"
                type="email"
                placeholder="you@example.com"
                :errors="errors"
            />

            <FormField
                v-model="subject"
                name="subject"
                label="Subject"
                type="text"
                placeholder="Project update"
                :errors="errors"
            />

            <FormField
                v-model="message"
                name="message"
                label="Message"
                type="textarea"
                rows="6"
                placeholder="Tell us what you need."
                :errors="errors"
            />

            <button type="submit" class="btn btn--primary" @click="submit">
                Send message
            </button>

            <Alert
                v-if="serverErrors.length"
                :variant="serverErrors.length === 1 ? 'success' : 'danger'"
                :title="serverErrors.length === 1 ? 'Success' : 'Errors'"
                :message="serverErrors.join('\n')"
            />
        </div>
    </AppLayout>
</template>

<script setup lang="ts">
import { ref, computed } from 'vue';
import AppLayout from '@/layouts/AppLayout.vue';
import FormField from '@/components/FormField.vue';
import Alert from '@/components/Alert.vue';

interface FormData {
    email: string;
    subject: string;
    message: string;
}

interface FormErrors {
    [key: string]: string;
}

const props = defineProps<{
    appName?: string;
    serverErrors?: string[];
}>();

const emit = defineEmits<{
    submit: [data: FormData];
}>();

const email = ref('');
const subject = ref('');
const message = ref('');

const errors = computed<FormErrors>(() => {
    const values: FormErrors = {};
    if (!email.value) values.email = 'Email is required.';
    if (!subject.value) values.subject = 'Subject is required.';
    if (!message.value) values.message = 'Message is required.';
    return values;
});

const serverErrors = computed(() => props.serverErrors ?? []);

const submit = () => {
    emit('submit', {
        email: email.value,
        subject: subject.value,
        message: message.value,
    });
};
</script>

