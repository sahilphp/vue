<template>
    <div :class="['form__field', { 'form__field--error': errors.has(name) }]">
        <label :for="`field-${name}`" class="form__label">{{ label }}</label>
        <input
            :id="`field-${name}`"
            v-model="localValue"
            :type="type"
            :name="name"
            :required="required"
            :placeholder="placeholder"
            autocomplete="off"
        />
        <p v-if="errors.has(name)" class="form__error" role="alert">
            {{ errors.get(name) ?? 'This field is invalid.' }}
        </p>
    </div>
</template>

<script setup lang="ts">
import { computed } from 'vue';

export interface FormFieldProps {
    name: string;
    label: string;
    type?: string;
    placeholder?: string;
    required?: boolean;
    value?: string;
    errors: {
        has: (name: string) => boolean;
        get: (name: string) => string | undefined;
    };
}

withDefaults(defineProps<FormFieldProps>(), {
    type: 'text',
    placeholder: '',
    required: false,
});

const emit = defineEmits<{
    input: [value: string];
}>();

const localValue = computed({
    get: () => props.value ?? '',
    set: (value) => emit('input', value),
});
</script>

