<?php

declare(strict_types=1);

namespace Sahil\Frontend;

use Sahil\Http\Response;
use Sahil\View\RenderedView;
use Sahil\View\ViewEngine;

/** @deprecated Use Response::vue()/renderVue() */
function html(string|RenderedView $view, int $status = 200): Response
{
    return Response::html($view, $status);
}

/** @deprecated Use Response::vue() */
function vue(string|self|RenderedView $view, int $status = 200): Response
{
    return Response::vue($view, $status);
}

/** @deprecated Use Response::react() */
function react(string|self|RenderedView $view, int $status = 200): Response
{
    return Response::react($view, $status);
}

/** @deprecated Use Response::svelte() */
function svelte(string|self|RenderedView $view, int $status = 200): Response
{
    return Response::svelte($view, $status);
}
